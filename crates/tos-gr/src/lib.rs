//! TempleOS 16-color graphics. Filled in Phase 3.

pub fn palette_rgb(color: u8) -> [u8; 3] {
    // Standard TempleOS 16-color VGA-ish palette.
    match color & 0x0F {
        0 => [0x00, 0x00, 0x00],
        1 => [0x00, 0x00, 0xAA],
        2 => [0x00, 0xAA, 0x00],
        3 => [0x00, 0xAA, 0xAA],
        4 => [0xAA, 0x00, 0x00],
        5 => [0xAA, 0x00, 0xAA],
        6 => [0xAA, 0x55, 0x00],
        7 => [0xAA, 0xAA, 0xAA],
        8 => [0x55, 0x55, 0x55],
        9 => [0x55, 0x55, 0xFF],
        10 => [0x55, 0xFF, 0x55],
        11 => [0x55, 0xFF, 0xFF],
        12 => [0xFF, 0x55, 0x55],
        13 => [0xFF, 0x55, 0xFF],
        14 => [0xFF, 0xFF, 0x55],
        _ => [0xFF, 0xFF, 0xFF],
    }
}
